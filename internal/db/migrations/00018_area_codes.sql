-- +goose Up
-- Area codes (D-76): country code plus area code with a human description and
-- the operator, matched longest prefix first against the called number so
-- every CDR says where a call landed and on whose network.
CREATE TABLE area_codes (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    country_code text NOT NULL CHECK (country_code ~ '^[0-9]{1,4}$'),
    area_code    text NOT NULL DEFAULT '' CHECK (area_code ~ '^[0-9]*$'),
    -- The full E.164 prefix the number is matched against.
    prefix       text GENERATED ALWAYS AS (country_code || area_code) STORED,
    country      text NOT NULL DEFAULT '',
    description  text NOT NULL,
    operator     text NOT NULL DEFAULT '',
    kind         text NOT NULL DEFAULT 'mobile' CHECK (kind IN ('mobile', 'fixed', 'other')),
    enabled      boolean NOT NULL DEFAULT true,
    notes        text NOT NULL DEFAULT '',
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (country_code, area_code)
);
-- One entry per full prefix, so a number never matches two rows of equal length
-- ("243" + "81" and "24" + "381" would otherwise both be 24381).
CREATE UNIQUE INDEX area_codes_prefix_key ON area_codes (prefix);
CREATE TRIGGER area_codes_updated BEFORE UPDATE ON area_codes
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE cdrs
    ADD COLUMN area_prefix text,
    ADD COLUMN area_description text,
    ADD COLUMN operator_name text;

